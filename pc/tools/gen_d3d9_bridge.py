"""Generates the guest->host Direct3D 9 bridge (pc/runtime/rt_d3d9_gen.c) from d3d9.h.

Every method of the 17 D3D9 interfaces gets an HLE thunk: the guest calls it through a guest
vtable (stdcall, `this` first); the thunk converts the 32-bit guest arguments and calls the host
object through its own vtable by index. Parameter kinds:
  scalar        DWORD, UINT, INT, BOOL, enums, D3DCOLOR   -> passed as is
  float         float                                     -> float
  ptr           pointers to plain structs / arrays / data -> guest address -> host pointer (layouts
                are identical in 32 and 64 bits for structs without pointer or handle fields)
  iface_in      IDirect3DXxx9*                            -> host object of the guest proxy
  iface_out     IDirect3DXxx9**                           -> host result wrapped in a guest proxy
  hwnd          HWND                                      -> host window of the guest window
  shared        HANDLE* (shared handles)                  -> NULL
Methods whose structs carry pointers or handles, and Lock/Unlock, are written by hand in
rt_d3d9.c (SPECIAL below); the generator emits a reference to them instead.

  python -I outputs/mirrors-edge-native/pc/tools/gen_d3d9_bridge.py \
      work/references/dxvk/include/native/directx/d3d9.h outputs/mirrors-edge-native/pc/runtime/rt_d3d9_gen.c
"""
import re
import sys

IFACES = ["IDirect3D9", "IDirect3DDevice9", "IDirect3DSwapChain9", "IDirect3DResource9", "IDirect3DSurface9",
          "IDirect3DVolume9", "IDirect3DVertexBuffer9", "IDirect3DIndexBuffer9", "IDirect3DBaseTexture9",
          "IDirect3DTexture9", "IDirect3DCubeTexture9", "IDirect3DVolumeTexture9", "IDirect3DVertexDeclaration9",
          "IDirect3DVertexShader9", "IDirect3DPixelShader9", "IDirect3DStateBlock9", "IDirect3DQuery9"]
CONCRETE = [i for i in IFACES if i not in ("IDirect3DResource9", "IDirect3DBaseTexture9")]

# Methods implemented by hand in rt_d3d9.c (any interface).
SPECIAL = {"QueryInterface", "AddRef", "Release", "CreateDevice", "Reset", "CreateAdditionalSwapChain",
           "GetPresentParameters", "GetCreationParameters", "GetAdapterIdentifier", "GetAdapterMonitor", "LockRect", "UnlockRect",
           "LockBox", "UnlockBox", "Lock", "Unlock", "GetDC", "ReleaseDC", "GetContainer"}

SCALARS = {"DWORD", "UINT", "INT", "int", "WINBOOL", "BOOL", "D3DCOLOR", "LONG", "ULONG"}


def parse(path):
    s = open(path, encoding="latin-1").read()
    ifaces = {}
    for m in re.finditer(r"DECLARE_INTERFACE_\((IDirect3D\w+),\s*(\w+)\)\s*\{(.*?)\};", s, re.S):
        name, base, body = m.group(1), m.group(2), m.group(3)
        methods = []
        # STDMETHOD(Name)(params) or STDMETHOD_(type, Name)(params)
        for mm in re.finditer(r"STDMETHOD(?:_\(\s*([^,()]+?)\s*,\s*(\w+)\s*\)|\((\w+)\))\s*\((.*?)\)\s*PURE", body, re.S):
            ret = (mm.group(1) or "HRESULT").strip()
            mname = mm.group(2) or mm.group(3)
            params = []
            for p in mm.group(4).replace("THIS_", "").replace("THIS", "").split(","):
                p = re.sub(r"\s+", " ", p.strip())
                if not p:
                    continue
                pm = re.match(r"(.*?)(\w+)$", p)
                ptype = pm.group(1).replace(" *", "*").strip() if pm and ("*" in p or " " in p) else p
                if pm and not ptype:
                    ptype = p
                params.append(ptype.replace("struct ", "").replace("CONST ", "const ").strip())
            methods.append((mname, ret, params))
        ifaces[name] = (base, methods)
    return ifaces


def flatten(ifaces, name):
    # The header lists every inherited method (IUnknown included) inside each interface block,
    # in vtable order, so a block alone is the complete vtable.
    return ifaces[name][1]


def kind(t):
    t = t.replace("const ", "").strip()
    if t in SCALARS or (t.startswith("D3D") and "*" not in t):
        return "scalar"
    if t == "float":
        return "float"
    if t == "HWND":
        return "hwnd"
    if t == "HANDLE*":
        return "shared"
    if t in ("REFGUID", "REFIID"):
        return "ptr"
    m = re.match(r"(IDirect3D\w*9)\s*\*\*$", t)
    if m:
        return "iface_out:" + m.group(1)
    m = re.match(r"(IDirect3D\w*9)\s*\*$", t)
    if m:
        return "iface_in"
    if t.endswith("*"):
        return "ptr"
    return "unknown:" + t


def ret_kind(r):
    r = r.strip()
    if r == "float":
        return "float"
    if r in ("HMONITOR",):
        return "unknown"
    if r == "void":
        return "void"
    return "u32"


def main():
    hdr, out = sys.argv[1], sys.argv[2]
    ifaces = parse(hdr)
    lines = ["/* Generated by pc/tools/gen_d3d9_bridge.py from DXVK's d3d9.h: guest D3D9 method thunks.",
             "   Do not edit; special methods live in rt_d3d9.c. */",
             '#include "rt_d3d9.h"', ""]
    tables = []
    unknown = set()
    for name in CONCRETE:
        methods = flatten(ifaces, name)
        entries = []
        for idx, (mname, ret, params) in enumerate(methods):
            sym = f"{name}_{mname}"
            if mname in SPECIAL:
                entries.append((mname, f"d3d_special_{mname}", 1 + len(params)))
                continue
            kinds = [kind(p) for p in params]
            bad = [k for k in kinds if k.startswith("unknown")]
            rk = ret_kind(ret)
            if bad or rk == "unknown":
                unknown.add(f"{name}::{mname} {params} -> {ret}")
                entries.append((mname, "d3d_unsupported", 1 + len(params)))
                continue
            ctypes, cargs, pre, post = ["void *"], ["self"], [], []
            for i, k in enumerate(kinds):
                a = f"ARG({i + 1})"
                if k == "scalar":
                    ctypes.append("uint32_t"); cargs.append(a)
                elif k == "float":
                    ctypes.append("float"); cargs.append(f"u2f({a})")
                elif k == "ptr":
                    ctypes.append("void *"); cargs.append(f"D3D_PTR({a})")
                elif k == "hwnd":
                    ctypes.append("void *"); cargs.append(f"d3d_host_hwnd({a})")
                elif k == "shared":
                    ctypes.append("void *"); cargs.append("NULL")
                elif k == "iface_in":
                    ctypes.append("void *"); cargs.append(f"d3d_host({a})")
                elif k.startswith("iface_out:"):
                    t = k.split(":", 1)[1]
                    ctypes.append("void **"); cargs.append(f"&out{i}")
                    pre.append(f"void *out{i} = NULL;")
                    post.append(f"if ({a}) st32({a}, out{i} ? d3d_wrap(out{i}, D3D_{t}) : 0);")
            rtype = "float" if rk == "float" else "uint32_t"
            fn = f"(({rtype} (D3D_CALL *)({', '.join(ctypes)}))D3D_VT(self)[{idx}])"
            body = [f"static void {sym}(X86Ctx *ctx)", "{", "    void *self = d3d_host(ARG(0));"]
            body += ["    " + p for p in pre]
            if rk == "void":
                body.append(f"    {fn.replace('(uint32_t (D3D_CALL', '(void (D3D_CALL')}({', '.join(cargs)});")
                body += ["    " + p for p in post]
            elif rk == "float":
                body.append(f"    float r = {fn}({', '.join(cargs)});")
                body += ["    " + p for p in post]
                body.append("    x87_push(ctx, (double)r); /* float results come back in ST(0) */")
            else:
                body.append(f"    uint32_t r = {fn}({', '.join(cargs)});")
                body += ["    " + p for p in post]
                body.append("    ctx->eax = r;")
            body += ["}", ""]
            lines += body
            entries.append((mname, sym, 1 + len(params)))
        tables.append((name, entries))
    for name, entries in tables:
        lines.append(f"static const D3dMethod methods_{name}[] = {{")
        for mname, sym, nargs in entries:
            lines.append(f'    {{"{name}::{mname}", {sym}, {nargs}}},')
        lines.append("};")
        lines.append("")
    # Interface IDs, for QueryInterface/GetContainer.
    src = open(hdr, encoding="latin-1").read()
    lines.append("const D3dIid d3d_iids[] = {")
    for m in re.finditer(r"DEFINE_GUID\(IID_(IDirect3D\w*9),\s*([^)]*)\)", src):
        if m.group(1) not in IFACES:
            continue
        v = [int(x.strip(), 16) for x in m.group(2).split(",")]
        b8 = ", ".join(f"0x{x:02X}" for x in v[3:])
        lines.append(f"    {{D3D_{m.group(1)}, {{0x{v[0]:08X}, 0x{v[1]:04X}, 0x{v[2]:04X}, {{{b8}}}}}}},")
    lines.append("};")
    lines.append("const uint32_t d3d_iids_count = sizeof d3d_iids / sizeof *d3d_iids;")
    lines.append("")
    lines.append("const D3dIfaceTable d3d_iface_tables[D3D_IFACE_COUNT] = {")
    for name, entries in tables:
        lines.append(f'    [D3D_{name}] = {{"{name}", methods_{name}, {len(entries)}}},')
    lines.append("};")
    open(out, "w", newline="\n").write("\n".join(lines) + "\n")
    # Host vtable indices for the hand-written methods.
    idx_lines = ["/* Generated by pc/tools/gen_d3d9_bridge.py: host vtable indices. */", "#pragma once"]
    for name in CONCRETE:
        for idx, (mname, _, _) in enumerate(flatten(ifaces, name)):
            idx_lines.append(f"#define D3D_IDX_{name}_{mname} {idx}")
    open(out.replace("_gen.c", "_idx.h"), "w", newline="\n").write("\n".join(idx_lines) + "\n")
    print(f"{sum(len(e) for _, e in tables)} thunks in {len(tables)} interfaces -> {out}")
    for u in sorted(unknown):
        print("unsupported:", u)


if __name__ == "__main__":
    main()
