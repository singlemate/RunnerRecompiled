/* Runtime of the lifted PC game: guest memory, modules, dispatch, threads, HLE imports.

   Guest memory is a 4 GB reservation; a guest address is an offset from x86_mem_base. Lifted
   modules are loaded at fixed guest bases; their import slots get guest addresses of exports
   of other lifted modules or of HLE thunks (a reserved range that x86_dispatch recognizes). */
#ifndef RT_H
#define RT_H

#include <stdint.h>
#include <stddef.h>
#include "x86rt.h"
#include "x86rt_module.h"

#ifndef _WIN32
#include <strings.h>
#define _stricmp strcasecmp
#define _strnicmp strncasecmp
#endif

/* --- host layer (rt_host_*.c) --- */
void *host_reserve(size_t size);
int host_commit(void *p, size_t size);       /* read/write */
int host_decommit(void *p, size_t size);
typedef struct HostMutex HostMutex;
HostMutex *host_mutex_new(void);
void host_lock(HostMutex *m);
void host_unlock(HostMutex *m);
uint64_t host_ticks_ns(void);                /* monotonic */
uint64_t host_filetime(void);                /* 100 ns since 1601-01-01 UTC */
void host_sleep_ms(uint32_t ms);
uint32_t host_thread_id(void);
void host_install_fault_handler(void);
typedef struct HostCond HostCond;
HostCond *host_cond_new(void);
/* Waits with m held; returns 0 on timeout. timeout_ms 0xFFFFFFFF = forever. */
int host_cond_wait(HostCond *c, HostMutex *m, uint32_t timeout_ms);
void host_cond_broadcast(HostCond *c);
int host_thread_start(void (*fn)(void *), void *arg);

/* --- guest memory --- */
#define RT_PAGE 0x1000u
#define RT_GRANULE 0x10000u
void rt_mem_init(void);
/* VirtualAlloc-like: addr 0 = anywhere. Returns the guest address or 0. */
uint32_t rt_vm_reserve(uint32_t addr, uint32_t size);
int rt_vm_commit(uint32_t addr, uint32_t size);
int rt_vm_release(uint32_t addr);
int rt_vm_is_committed(uint32_t addr);
uint32_t rt_vm_region_size(uint32_t addr, uint32_t *base, int *committed);
static inline void *rt_ptr(uint32_t a) { return (void *)X86_PTR(a); }

/* Guest heap (HeapAlloc/malloc of HLE code): thread-safe, memory inside guest space. */
uint32_t rt_heap_alloc(uint32_t size, int zero);
void rt_heap_free(uint32_t p);
uint32_t rt_heap_size(uint32_t p);
uint32_t rt_heap_realloc(uint32_t p, uint32_t size, int zero);

/* --- modules --- */
typedef struct RtModule {
    char name[64];       /* lower case, e.g. "msvcr80.dll" */
    uint32_t base, size, entry;
    int is_dll;
    const X86FnEntry *fns;
    uint32_t nfns;
    struct RtExport { char name[512]; uint32_t addr; uint16_t ordinal; } *exports;
    uint32_t nexports;
    int initialized;     /* DllMain(PROCESS_ATTACH) has run */
    struct RtModule *deps[16]; /* lifted modules this one imports from (filled by rt_resolve_imports) */
    int ndeps;
} RtModule;

/* A lifted module the runtime loads at start-up (table generated by build_pc_runtime.py). */
typedef struct RtModuleSpec {
    const char *name;    /* guest module name, lower case */
    const char *dir;     /* "game" (the game's Binaries), "deps" or "rebased" (rebased copies) */
    const char *file;
    const X86FnEntry *fns;
    const uint32_t *nfns;
    int init_at_start;   /* DllMain at start-up, else on the first LoadLibrary */
} RtModuleSpec;
extern const RtModuleSpec rt_module_specs[];
extern const int rt_module_spec_count;
/* Runs DllMain(PROCESS_ATTACH) of a DLL once. */
void rt_module_init(RtModule *m, X86Ctx *ctx);
/* Initializes m's imported modules first (depth first), then m: the Windows loader's order for
   statically imported DLLs. */
void rt_module_init_tree(RtModule *m, X86Ctx *ctx);

RtModule *rt_load_module(const char *path, const char *name, const X86FnEntry *fns, uint32_t nfns);
RtModule *rt_find_module(const char *name);
RtModule *rt_module_at(uint32_t addr);
uint32_t rt_export(RtModule *m, const char *name);   /* "#N" for ordinals; 0 if absent */
void rt_resolve_imports(RtModule *m);

/* --- HLE --- */
typedef void (*HleFn)(X86Ctx *ctx);
typedef struct HleDef { const char *dll, *name; HleFn fn; uint8_t nargs; } HleDef; /* stdcall args */
#define RT_THUNK_BASE 0xFE000000u
#define RT_THUNK_STEP 4u
void rt_hle_register(const HleDef *defs, size_t n);
uint32_t rt_hle_thunk(const char *dll, const char *name);  /* thunk address; unknown names get a "missing" thunk */
static inline uint32_t rt_arg(X86Ctx *ctx, int i) { return ld32(ctx->esp + 4 + 4u * (uint32_t)i); }
const char *rt_str(uint32_t a);             /* guest char* as host pointer (0 -> NULL) */

/* --- threads --- */
typedef struct RtThread {
    X86Ctx ctx;
    uint32_t teb, stack_base, stack_size, id;
    uint32_t last_error;
    volatile uint32_t last_target, last_ret, in_hle; /* diagnostics: last dispatch; inside an HLE call */
    X86Resume *resume_top;   /* innermost live frame with EH resume points */
    void *dcache;            /* dispatch cache (rt_core.c) */
    uint32_t host_tid;       /* host thread id (profiler) */
    struct { uint32_t thunk, esp, ret, eax_after; } hle_ring[64]; /* this thread's last HLE calls */
    uint32_t hle_pos;
    char name[32];           /* set by the guest (MS_VC_EXCEPTION), for diagnostics */
} RtThread;
void rt_start_stall_watch(void);
RtThread *rt_thread_self(void);
uint32_t rt_peb(void);
RtThread *rt_thread_create_main(uint32_t stack_size);
RtThread *rt_thread_new(uint32_t stack_size);   /* guest stack and TEB for a new thread */
void rt_thread_bind(RtThread *t);               /* make t the current guest thread of this host thread */
void rt_thread_set_name(uint32_t id, const char *name);    /* guest thread id (0xFFFFFFFF = calling thread) */
int rt_thread_list(uint32_t *host_tids, const char **names, int max); /* registered guest threads */
#define RT_TLS_SLOTS 1088 /* 64 in the TEB + 1024 expansion slots, as on Windows */
uint32_t rt_tls_alloc(void);
int rt_tls_free(uint32_t slot);
uint32_t rt_tls_get(uint32_t slot);
int rt_tls_set(uint32_t slot, uint32_t v);

/* Calls a guest function from the host (stdcall or cdecl; the args are pushed right to left). */
uint32_t rt_call(X86Ctx *ctx, uint32_t fn, int nargs, const uint32_t *args);

/* --- handles (rt_sync.c) --- */
enum { RT_H_FILE = 1, RT_H_FIND, RT_H_EVENT, RT_H_MUTEX, RT_H_SEMAPHORE, RT_H_THREAD, RT_H_MAPPING };
uint32_t rt_handle_new(int type, void *data);
void *rt_handle_data(uint32_t h, int type);
void rt_handle_close(uint32_t h);

/* --- host file system (UTF-8 paths) --- */
int host_open(const char *path, int write, int create, int truncate); /* fd or -1 */
int64_t host_read(int fd, void *buf, uint32_t n);
int64_t host_write(int fd, const void *buf, uint32_t n);
int64_t host_seek(int fd, int64_t off, int whence);  /* 0 set, 1 cur, 2 end */
int host_truncate(int fd, int64_t size);
void host_close(int fd);
/* kind: 0 missing, 1 file, 2 directory */
int host_stat(const char *path, int64_t *size, uint64_t *filetime);
int host_mkdir(const char *path);
int host_rmdir(const char *path);
int host_unlink(const char *path);
int host_rename(const char *from, const char *to);
/* Directory listing: calls fn for every entry name except "." and ".."; returns 0 if not a directory. */
int host_list_dir(const char *path, void (*fn)(void *u, const char *name), void *u);

/* --- diagnostics --- */
void rt_log(const char *fmt, ...);
void rt_fatal(const char *fmt, ...) __attribute__((noreturn));

#endif
